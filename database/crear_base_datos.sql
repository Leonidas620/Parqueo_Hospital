-- Esquema completo de la base de datos "parqueo_hospital" (PostgreSQL).
-- Si ya tiene una base creada con la versión anterior, ejecute migracion_turno_de_cobro.sql en lugar de este script.

CREATE TABLE IF NOT EXISTS cuentas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    usuario VARCHAR(60) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(10) NOT NULL CHECK (rol IN ('ADMIN', 'PARKER')),
    creado_en TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);

CREATE TABLE IF NOT EXISTS vehiculos (
    chapa VARCHAR(7) PRIMARY KEY CHECK (chapa ~ '^[PBFW][0-9]{6}$'),
    tipo VARCHAR(10) NOT NULL CHECK (tipo IN ('AUTO', 'MOTO', 'TRICICLO')),
    color VARCHAR(50) NOT NULL,
    marca VARCHAR(70) NOT NULL,
    propietario VARCHAR(120) NOT NULL,
    telefono VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS tarifas (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    tarifa_auto NUMERIC(10,2) NOT NULL DEFAULT 100 CHECK (tarifa_auto >= 0),
    tarifa_moto NUMERIC(10,2) NOT NULL DEFAULT 50 CHECK (tarifa_moto >= 0),
    tarifa_nocturna NUMERIC(10,2) NOT NULL DEFAULT 20 CHECK (tarifa_nocturna >= 0)
);

-- Capacidad configurable por el administrador. Los triciclos ocupan espacios de autos.
CREATE TABLE IF NOT EXISTS capacidad (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    capacidad_autos INTEGER NOT NULL DEFAULT 40 CHECK (capacidad_autos >= 0),
    capacidad_motos INTEGER NOT NULL DEFAULT 30 CHECK (capacidad_motos >= 0)
);

CREATE TABLE IF NOT EXISTS turnos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    parqueador_id BIGINT NOT NULL REFERENCES cuentas(id) ON DELETE RESTRICT,
    hora_inicio TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP,
    hora_fin TIMESTAMP,
    total NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
    CHECK (hora_fin IS NULL OR hora_fin >= hora_inicio)
);

-- turno_id es el turno de quien COBRA: queda vacío mientras el vehículo está dentro
-- y se asigna al registrar la salida. El parqueador del servicio se obtiene a través del turno.
CREATE TABLE IF NOT EXISTS servicios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapa VARCHAR(7) NOT NULL REFERENCES vehiculos(chapa) ON DELETE RESTRICT,
    hora_entrada TIMESTAMP NOT NULL,
    hora_salida TIMESTAMP,
    tarifa_aplicada NUMERIC(10,2) NOT NULL CHECK (tarifa_aplicada >= 0),
    importe NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (importe >= 0),
    turno_id BIGINT REFERENCES turnos(id) ON DELETE RESTRICT,
    CHECK (hora_salida IS NULL OR hora_salida >= hora_entrada),
    CONSTRAINT servicios_turno_coherente CHECK ((hora_salida IS NULL) = (turno_id IS NULL))
);

-- Cualquier chapa válida puede abonarse, haya entrado o no antes al parqueo.
CREATE TABLE IF NOT EXISTS abonos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chapa VARCHAR(7) NOT NULL CHECK (chapa ~ '^[PBFW][0-9]{6}$'),
    mes SMALLINT NOT NULL CHECK (mes BETWEEN 1 AND 12),
    anio SMALLINT NOT NULL CHECK (anio BETWEEN 2000 AND 2200),
    importe NUMERIC(12,2) NOT NULL CHECK (importe >= 0),
    UNIQUE (chapa, mes, anio)
);

-- Días que el administrador ya cuadró.
CREATE TABLE IF NOT EXISTS cuadres_dia (
    fecha DATE PRIMARY KEY,
    total NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    creado_en TIMESTAMP NOT NULL DEFAULT LOCALTIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_turno_abierto_por_parqueador
    ON turnos(parqueador_id) WHERE hora_fin IS NULL;
CREATE UNIQUE INDEX IF NOT EXISTS uq_cuentas_usuario_sin_distinguir_mayusculas
    ON cuentas(LOWER(usuario));
CREATE UNIQUE INDEX IF NOT EXISTS uq_servicio_activo_por_chapa
    ON servicios(chapa) WHERE hora_salida IS NULL;
CREATE INDEX IF NOT EXISTS ix_servicios_salida ON servicios(hora_salida);
CREATE INDEX IF NOT EXISTS ix_servicios_turno ON servicios(turno_id);
CREATE INDEX IF NOT EXISTS ix_abonos_vehiculo_mes ON abonos(chapa, anio, mes);

